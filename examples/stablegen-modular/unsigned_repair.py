"""Repair generated triangle soup through unsigned occupancy, never signed booleans.

CPU example: numpy, scipy and scikit-image are explicit dependencies, not installed
by this script. Geometry only; UVs, materials, rig and morphs are not transferred.

python unsigned_repair.py --source postfloor.glb --outputfolder repaired \
  --closing-sizes 9 13 --min-solid-voxels 1800000 --repair-config case.json

A repair-config is OPTIONAL and explicitly case-specific:
{"region":{"min":[null,-0.13,-0.13],"max":[null,null,null]},
 "ellipsoid":{"center":[0,-0.065,-0.05],"radii":[0.146,0.19,0.14]},
 "protect_ellipsoids":[{"center":[0.12,-0.18,0.075],"radii":[0.055,0.065,0.06]}],
 "remove_boxes":[{"min":[null,null,0.108],"max":[null,null,null]}]}

Do not apply example coordinates to a different animal. An ellipsoidal local
repair is manual anatomical inference, not geometry generated by the AI. Keep
face/feet protected and review the bare model before adding modular equipment.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import struct
import time


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', required=True, type=Path)
    parser.add_argument('--outputfolder', '--output-folder', dest='outputfolder', required=True, type=Path)
    parser.add_argument('--resolution', type=int, default=256, help='Longest grid dimension including padding; increase only after measuring.')
    parser.add_argument('--padding', type=int, help='Explicit voxel padding for a recorded case; otherwise sized for the closing kernel.')
    parser.add_argument('--closing-sizes', type=int, nargs='+', default=[5], help='Odd box sizes. Closing may erase fingers or intended cavities.')
    parser.add_argument('--min-solid-voxels', type=int, help='Optional CASE-SPECIFIC criterion for trying the next closing size; not an anatomy test.')
    parser.add_argument('--component-policy', choices=['all', 'largest'], default='all')
    parser.add_argument('--repair-config', type=Path)
    parser.add_argument('--sigma', type=float, default=0.6)
    parser.add_argument('--isovalue', type=float, default=0.501)
    parser.add_argument('--threads', type=int, default=4)
    args = parser.parse_args()
    if not 32 <= args.resolution <= 512 or any(n < 1 or n % 2 == 0 for n in args.closing_sizes):
        raise ValueError('Resolution 32..512 and positive odd closing sizes required.')
    for key in ('OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'VECLIB_MAXIMUM_THREADS', 'NUMEXPR_NUM_THREADS'):
        os.environ[key] = str(args.threads)
    import numpy as np
    from scipy import ndimage as ndi
    from skimage.measure import marching_cubes
    source, out = args.source.resolve(), args.outputfolder.resolve()
    if source.suffix.lower() != '.glb':
        raise ValueError('A static, single-mesh generated GLB is expected.')
    out.mkdir(parents=True, exist_ok=True)
    data = source.read_bytes()
    if data[:4] != b'glTF':
        raise ValueError('Invalid GLB header.')
    json_size = struct.unpack_from('<I', data, 12)[0]
    doc = json.loads(data[20:20 + json_size])
    binary_start = 28 + json_size
    if len(doc.get('meshes', [])) != 1 or len(doc['meshes'][0]['primitives']) != 1 or doc.get('skins'):
        raise ValueError('Do not silently merge modules or discard skins; supply one static surface.')
    node = next((n for n in doc.get('nodes', []) if n.get('mesh') == 0), {})
    if any(k in node for k in ('matrix', 'translation', 'rotation', 'scale')):
        raise ValueError('Apply transforms in a geometry checkpoint first; this helper expects identity mesh transforms.')
    types = {5126: '<f4', 5125: '<u4', 5123: '<u2', 5121: 'u1'}
    widths = {'SCALAR': 1, 'VEC3': 3}
    def accessor(index):
        a = doc['accessors'][index]
        bv = doc['bufferViews'][a['bufferView']]
        if a.get('sparse') or bv.get('byteStride'):
            raise ValueError('Deinterleave/sparsity must be resolved before this geometry helper.')
        return np.frombuffer(data, dtype=types[a['componentType']], count=a['count'] * widths[a['type']],
                             offset=binary_start + bv.get('byteOffset', 0) + a.get('byteOffset', 0)).reshape(-1, widths[a['type']]).copy()
    primitive = doc['meshes'][0]['primitives'][0]
    if primitive.get('mode', 4) != 4 or primitive.get('targets'):
        raise ValueError('Triangle geometry before morphs is required.')
    vertices = accessor(primitive['attributes']['POSITION'])[:, [0, 2, 1]]
    vertices[:, 1] *= -1  # Standard glTF Y-up -> Blender Z-up, not a guessed source rotation.
    faces = accessor(primitive['indices']).reshape(-1, 3).astype(np.int32)
    if not np.isfinite(vertices).all():
        raise ValueError('Nonfinite input coordinates.')
    start = time.monotonic()
    padding = args.padding if args.padding is not None else max(6, max(args.closing_sizes) // 2 + 1)
    if padding < 1 or 2 * padding >= args.resolution:
        raise ValueError('Invalid grid padding.')
    pitch = float(np.ptp(vertices, axis=0).max() / (args.resolution - 2 * padding))
    origin = vertices.min(0) - padding * pitch
    dims = np.ceil((vertices.max(0) - origin) / pitch).astype(int) + padding + 1
    occupied = np.zeros(dims, dtype=bool)
    def raster(points):
        q = np.rint((points - origin) / pitch).astype(np.int32)
        q = np.minimum(np.maximum(q, 0), dims - 1)
        occupied[q[:, 0], q[:, 1], q[:, 2]] = True
    triangles = vertices[faces]
    raster(vertices)
    raster(triangles.mean(1))
    edges = np.maximum.reduce([np.linalg.norm(triangles[:, 1] - triangles[:, 0], axis=1),
                               np.linalg.norm(triangles[:, 2] - triangles[:, 1], axis=1),
                               np.linalg.norm(triangles[:, 0] - triangles[:, 2], axis=1)])
    subdivisions = np.clip(np.ceil(edges / pitch * 1.2).astype(int), 1, 128)
    for n in np.unique(subdivisions):
        indices = np.where(subdivisions == n)[0]
        weights = np.array([(i / n, j / n) for i in range(n + 1) for j in range(n + 1 - i)], np.float32)
        batch_size = max(1, 500000 // len(weights))
        for k in range(0, len(indices), batch_size):
            t = triangles[indices[k:k + batch_size]]
            points = t[:, 0, None, :] + weights[None, :, 0, None] * (t[:, 1, None, :] - t[:, 0, None, :]) + weights[None, :, 1, None] * (t[:, 2, None, :] - t[:, 0, None, :])
            raster(points.reshape(-1, 3))
    attempts = []
    for closing_size in args.closing_sizes:
        closed = ndi.minimum_filter(ndi.maximum_filter(occupied, size=closing_size, mode='constant', cval=0),
                                    size=closing_size, mode='constant', cval=0)
        filled = ndi.binary_fill_holes(closed)
        labels, component_count = ndi.label(filled)
        sizes = np.bincount(labels.ravel())
        sizes[0] = 0
        if not sizes.any():
            raise ValueError('No occupied component survived.')
        volume = labels == int(sizes.argmax()) if args.component_policy == 'largest' else filled
        attempts.append({'closing_size': closing_size, 'surface_voxels': int(closed.sum()),
                         'solid_voxels': int(volume.sum()), 'component_sizes': sorted(sizes.tolist(), reverse=True)[:16]})
        if args.min_solid_voxels is None or volume.sum() >= args.min_solid_voxels:
            break
    if args.min_solid_voxels is not None and volume.sum() < args.min_solid_voxels:
        raise ValueError('Case-specific solid-volume criterion not reached; do not describe a hollow shell as repaired.')
    x = origin[0] + np.arange(dims[0]) * pitch
    y = origin[1] + np.arange(dims[1]) * pitch
    z = origin[2] + np.arange(dims[2]) * pitch
    X, Y, Z = x[:, None, None], y[None, :, None], z[None, None, :]
    coordinates = (X, Y, Z)
    def box_mask(box):
        mask = np.ones(dims, dtype=bool)
        for axis, c in enumerate(coordinates):
            low, high = box['min'][axis], box['max'][axis]
            if low is not None:
                mask &= np.broadcast_to(c > low, dims)
            if high is not None:
                mask &= np.broadcast_to(c < high, dims)
        return mask
    def ellipsoid(e):
        return sum(((c - e['center'][i]) / e['radii'][i]) ** 2 for i, c in enumerate(coordinates)) <= 1
    config = json.loads(args.repair_config.read_text(encoding='utf-8')) if args.repair_config else None
    changed_voxels = 0
    if config:
        region = box_mask(config['region'])
        for protection in config.get('protect_ellipsoids', []):
            region &= ~np.broadcast_to(ellipsoid(protection), dims)
        replacement = np.broadcast_to(ellipsoid(config['ellipsoid']), dims)
        changed_voxels = int(np.count_nonzero(volume[region] != replacement[region]))
        volume[region] = replacement[region]
        for removal in config.get('remove_boxes', []):
            volume[box_mask(removal)] = False
        volume = ndi.minimum_filter(ndi.maximum_filter(volume, size=5, mode='constant', cval=0), size=5, mode='constant', cval=0)
        volume = ndi.binary_fill_holes(volume)
    field = ndi.gaussian_filter(volume.astype(np.float32), sigma=args.sigma)
    verts, tris, _, _ = marching_cubes(field, level=args.isovalue, spacing=(pitch, pitch, pitch), allow_degenerate=False)
    verts += origin
    # Keep coherent outward orientation for mesh importers using back-face culling.
    signed_volume = float(np.einsum('ij,ij->i', verts[tris[:, 0]], np.cross(verts[tris[:, 1]], verts[tris[:, 2]])).sum() / 6)
    if signed_volume < 0:
        tris = tris[:, ::-1]
        signed_volume *= -1
    np.savez_compressed(out / 'surface.npz', vertices=verts, faces=tris)
    with (out / 'surface.ply').open('wb') as handle:
        handle.write(('ply\nformat binary_little_endian 1.0\nelement vertex %d\nproperty float x\nproperty float y\nproperty float z\nelement face %d\nproperty list uchar int vertex_indices\nend_header\n' % (len(verts), len(tris))).encode('ascii'))
        handle.write(verts.astype('<f4').tobytes())
        packed = np.empty(len(tris), dtype=[('count', 'u1'), ('indices', '<i4', (3,))])
        packed['count'] = 3
        packed['indices'] = tris
        handle.write(packed.tobytes())
    report = {'source': source.name, 'source_sha256': hashlib.sha256(data).hexdigest(),
              'grid': dims.tolist(), 'padding': padding, 'pitch': pitch, 'sampled_surface_voxels': int(occupied.sum()),
              'closing_attempts': attempts, 'component_policy': args.component_policy,
              'manual_repair_config': config, 'manual_changed_voxels': changed_voxels,
              'final_solid_voxels': int(volume.sum()), 'sigma': args.sigma, 'isovalue': args.isovalue,
              'vertices': len(verts), 'triangles': len(tris), 'signed_volume': signed_volume,
              'bounds': {'min': verts.min(0).tolist(), 'max': verts.max(0).tolist()},
              'seconds': time.monotonic() - start,
              'limits': 'Geometry reconstruction changes contour and may close intended cavities. No anatomy, material, rig, fit, engine or mobile-performance approval. Review the bare body from all sides before accessories.'}
    (out / 'surface-report.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print('UNSIGNED_REPAIR_WRITTEN', len(verts), len(tris), flush=True)


if __name__ == '__main__':
    main()
